import assert from 'node:assert/strict';
import { applyPatch } from 'diff';
import { changeHunk, filePatch, recordCorrection, reviewDiff, reviewHistory } from '../src/pages/AICollect/changeReview.ts';

const before = Array.from({length:40}, (_,i)=>`line ${i+1}\n`).join('');
const after = before.replace('line 3\n','corrected 3\n').replace('line 35\n','corrected 35\n');
const staged = changeHunk('adapter.py', before, after, 0, before);
assert.ok(staged.includes('corrected 3'));
assert.ok(staged.includes('line 35'));
assert.equal(changeHunk('adapter.py',before,after,0,after,true),after.replace('corrected 3','line 3'));
assert.equal(applyPatch(before,filePatch('adapter.py',before,after)),after);
assert.equal(changeHunk('adapter.py','', 'new\n',0,'new\n',true),'');
assert.equal(changeHunk('adapter.py','last line','corrected last line',0,'last line'),'corrected last line');
assert.throws(()=>changeHunk('adapter.py',before,after,100,before));
const whitespace = reviewDiff('adapter.py','value = 1\nother = 2\n','value =  1\nother = 3\n',true);
assert.equal(whitespace.hunks.reduce((sum,h)=>sum+h.additionLines,0),1);
assert.equal(whitespace.additionLines[0],'value =  1\n');
assert.equal(whitespace.additionCharacterCount,'value =  1\nother = 3\n'.length);
assert.equal(reviewDiff('x.py','','').hunks.length,0);
const first={id:1,prompt:'Generate',reply:'',template:'a: 1\n',adapter:'',step:5,done:6,complete:true};
const corrected=recordCorrection(first,{template:first.template,adapter:''},{template:'a: 2\n',adapter:''},'Fix');
assert.equal(first.review,undefined);
assert.equal(corrected.review.revisions.length,2);
assert.equal(corrected.review.revisions[0].template,'a: 1\n');
const fromSnapshot=recordCorrection(first,{...first,id:'response-1'},{template:'a: 3\n',adapter:'',id:'response-1'},'Fix snapshot');
assert.equal(fromSnapshot.id,1);
assert.equal(fromSnapshot.template,'a: 3\n');
assert.equal(reviewHistory([corrected]).length,2);
const reverted=recordCorrection(corrected,{template:'a: 2\n',adapter:''},{template:'',adapter:''},'Delete');
assert.equal(reviewHistory([reverted]).at(-1).template,'');
assert.equal(reverted.review.revisions.length,3);
assert.equal(recordCorrection(reverted,{template:'',adapter:''},{template:'',adapter:''},'Noop'),reverted);
console.log('Patch application, hunk staging/revert, whitespace coordinates and immutable corrections passed');
